export const buildAssetInwardExportRows = (rows = []) =>
  rows.map((row, index) => ({
    'Sr. No.': index + 1,
    asset_name: row.asset_name || '',
    asset_description: row.asset_description || '',
    property_id: row.property?.property_name || row.property_name || row.property_id || '',
    asset_code: row.asset_code || '',
    asset_type_id: row.asset_type || '',
    asset_category_id: row.category_name || row.category?.category_name || '',
    asset_sub_category_id: row.AssetSubCategory?.sub_category_name || row.sub_category_name || '',
    department_id: row.Department?.dept_name || row.department_name || row.department_id || '',
    first_name: row.first_name || '',
    last_name: row.last_name || '',
    state_id: row.state_id || '',
    city_id: row.city_id || '',
    make: row.make || '',
    quantity: row.quantity || '',
    location_id: row.location_name || row.location?.location_name || row.location_id || '',
    brand: row.brand || '',
    model: row.model || '',
    serial_no: row.serial_number || '',
    purchase_order_no: row.po_number || '',
    purchase_date: row.purchase_date || '',
    subdept_id: row.sub_department_id || '',
    note: row.remarks || '',
    supplier_id: row.Vendor?.vendor_name || row.vendor_name || row.vendor_id || '',
    invoice_number: row.invoice_number || '',
    purchase_cost: row.purchase_cost || '',
    gst: row.gst_eligible ?? '',
    total_cost: row.total_cost || ''
  }));
